use std::{
    env,
    path::{Path, PathBuf},
};

#[rustfmt::skip]
static HEADER: &str =
"/**
 * SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.
 * SPDX-License-Identifier: Apache-2.0
 */";

fn get_output_path() -> PathBuf {
    //<root or manifest path>/target/<profile>/
    let manifest_dir_string = env::var("CARGO_MANIFEST_DIR").unwrap();
    let build_type = env::var("PROFILE").unwrap();
    let path = Path::new(&manifest_dir_string)
        .join("..")
        .join("target")
        .join(build_type);
    path
}

fn main() {
    let client_file = Path::new("src/hub_client_c.rs");
    println!("cargo:rerun-if-changed={}", client_file.to_str().unwrap());

    let crate_dir = env::var("CARGO_MANIFEST_DIR").unwrap();
    let output_path = get_output_path().join("hub_client_bindings.h");

    cbindgen::Builder::new()
        .with_crate(crate_dir)
        .with_parse_deps(true)
        .with_parse_include(&["hub-rpc"])
        .with_language(cbindgen::Language::C)
        .with_style(cbindgen::Style::Type)
        .with_tab_width(4)
        .with_line_length(120)
        .with_autogen_warning(
            "/* Warning, this file is autogenerated by cbindgen. Do not modify this file manually. */",
        )
        .with_header(HEADER)
        .with_pragma_once(true)
        .with_item_prefix("OmniHub")
        .rename_item("ClientPutRequest", "PutRequest")
        .with_cpp_compat(true)
        .generate()
        .expect("Unable to generate bindings")
        .write_to_file(output_path);
}
