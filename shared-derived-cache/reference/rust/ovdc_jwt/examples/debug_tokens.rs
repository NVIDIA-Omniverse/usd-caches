fn main() {
    let key = EncodingKey::from_ec_der(DEBUG_KEY);
    let mut header = Header::new(Algorithm::ES256);
    header.kid = Some("debug".to_owned());

    let claims = |tenant: &str| {
        json!({
            "iss": "https://issuer.example.com",
            "sub": "example-service",
            "aud": "ovdc-test",
            "assertion": {
                "ncaId": tenant,
                "functionId": "example-function",
                "functionVersionId": "example-version"
            },
            "iat": 1700000000,
            "jti": format!("example-token-{tenant}")
        })
    };
    let first = claims("example-tenant-a");
    let second = claims("example-tenant-b");
    let mut missing = first.clone();
    missing["assertion"]
        .as_object_mut()
        .unwrap()
        .remove("ncaId");
    missing["exp"] = json!(4102444800u64);
    let mut expired = first.clone();
    expired["exp"] = json!(1700000000u64);

    for (name, payload) in [
        ("_DEBUG_JWT_0", first),
        ("_DEBUG_JWT_1", second),
        ("_DEBUG_BAD_JWT_MISSING_NID", missing),
        ("_DEBUG_BAD_JWT_EXPIRED", expired),
    ] {
        let jwt = encode::<Value>(&header, &payload, &key).expect("sign fixture");
        println!("pub const {name}: &str = \"{jwt}\";");
    }
}
